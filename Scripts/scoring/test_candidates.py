# Tests for a published cpu_seed42_v1 subset (CPU only, no torch):
#   integrity    every file's sha256 / dtype / shape matches MANIFEST.json, inputs (keys, Talos rows) unchanged
#   legality     rows inside the subset pool; anchors unique; positive in the anchor's group, other row, task
#                constraint holds; no negative in the anchor's group; P-1 negatives per query; query budget met
#                (Q = min(100,000, anchors with a valid positive))
#   determinism  queries, positives and every negative block regenerated from the seeds equal the published bytes
# Writes <root>/tests/<subset>.json. usage: test_candidates.py <root>/<subset>
import json, sys
from pathlib import Path
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sample_candidates as sc

d = Path(sys.argv[1]); subset = d.name
man = json.loads((d / "MANIFEST.json").read_text())
summary = json.loads((d / "summary.json").read_text())
assert man["complete"] and man["protocol"]["name"] == sc.PROTOCOL and summary["subset"] == subset
report = {"subset": subset, "protocol": sc.PROTOCOL, "checks": {}}

for rel, info in man["files"].items():
    f = d / rel
    assert f.stat().st_size == info["bytes"] and sc.sha256(f) == info["sha256"], rel
    if f.suffix == ".npy":
        m = np.load(f, mmap_mode="r"); assert str(m.dtype) == info["dtype"] and list(m.shape) == info["shape"], rel
# Frozen MANIFESTs record absolute input paths. If the data moved, map old prefixes to new ones with
# REGRAPH_PATH_MAP="old1=new1;old2=new2".
import os
MOVED = dict(kv.split("=", 1) for kv in os.environ.get("REGRAPH_PATH_MAP", "").split(";") if "=" in kv)


def local(path):
    for old, new in MOVED.items():
        if path.startswith(old + "/"):
            return new + path[len(old):]
    return path


for k, v in man["inputs"].items():
    if k != "script": assert sc.sha256(local(v["path"])) == v["sha256"], k
listed = {str(f.relative_to(d)) for f in d.rglob("*") if f.is_file()} - {"MANIFEST.json"}
assert listed == set(man["files"]), listed ^ set(man["files"])
report["checks"]["integrity"] = f"{len(man['files'])} files match MANIFEST sha256/dtype/shape; inputs unchanged"

ctx = sc.load_subset(subset)
pool, grp = ctx["pool"], ctx["grp"]
assert (np.load(d / "pool_rows.npy") == pool).all()
inpool = np.zeros(len(grp), bool); inpool[pool] = True
for t in sc.TASK_ID:
    a = np.load(d / t / "anchors.npy"); q = np.load(d / t / "positives.npy")
    n_valid = sum(any(j != i and sc.task_ok(ctx, t, i, j) for j in ctx["members"][grp[i]]) for i in map(int, pool))
    assert len(a) == len(q) == summary["tasks"][t]["queries"] == min(sc.MAXQ, n_valid), (t, len(a), n_valid)
    assert len(np.unique(a)) == len(a) and inpool[a].all() and inpool[q].all() and (a != q).all() and (grp[a] == grp[q]).all(), t
    assert all(sc.task_ok(ctx, t, int(i), int(j)) for i, j in zip(a, q)), t
    ra, rq = sc.sample_queries(ctx, t)
    assert (ra == a).all() and (rq == q).all(), t
    for P in sc.POOLS:
        nblk = summary["tasks"][t]["pools"][str(P)]["neg_files"]; seen = 0
        for k in range(nblk):
            n = np.load(d / t / f"neg_p{P}_{k:03d}.npy")
            aa = a[seen:seen + len(n)]
            assert n.dtype == np.uint32 and n.shape == (len(aa), P - 1), (t, P, k)
            assert inpool[n].all() and (grp[n] != grp[aa][:, None]).all(), (t, P, k)
            assert np.array_equal(sc.sample_negatives(ctx, t, P, k, a), n), ("determinism", t, P, k)
            seen += len(n)
        assert seen == len(a), (t, P)
    report["checks"][t] = {"queries": int(len(a)), "anchors_with_valid_positive": int(n_valid), "legality": "ok",
                           "determinism": f"queries, positives and {2 * nblk} negative blocks regenerated byte-identical"}
    print(subset, t, report["checks"][t], flush=True)
assert "torch" not in sys.modules
report["torch_imported"] = False
report["result"] = "PASS"
out = d.parent / "tests"; out.mkdir(exist_ok=True)
(out / f"{subset}.json").write_text(json.dumps(report, indent=1))
print(subset, "PASS", flush=True)
